package G01_Introduccion_I_E1;

/**
 * Programa Java inicial: muestra un mensaje en consola.
 * Explica la estructura mínima de una clase ejecutable en Java.
 */
public class holaMundo {

    // La palabra reservada class define una clase Java.
    // public permite que la clase sea accesible desde fuera del archivo.
    // static indica que el método pertenece a la clase y no necesita un objeto.
    // void significa que el método no devuelve ningún valor.
    public static void main(String[] args) {
        // System.out.println() imprime el texto en la salida estándar.
        System.out.println("Hola Mundo");
    }
}
